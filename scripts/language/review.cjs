// Developer-only language review. No dictionaries, Docker code or reports enter
// the JS bundle. Run from the repository root after fetching the pinned files.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');
const ts = require('typescript');
const root = path.resolve(__dirname, '../..');
process.chdir(root);
const read = p => JSON.parse(fs.readFileSync(p, 'utf8'));
function dictionary(p, symbol) {
  const exports = {};
  const code = ts.transpileModule(fs.readFileSync(p, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
  vm.runInNewContext(code, { exports });
  return exports[symbol];
}
const flatten = (d, prefix = '') => Object.entries(d).flatMap(([k,v]) => {
  const key = prefix ? `${prefix}.${k}` : k;
  return typeof v === 'string' ? [[key,v]] : flatten(v,key);
});
const en = new Map([...flatten(dictionary('src/i18n/shellStrings.ts','SHELL_STRINGS')), ...flatten(dictionary('src/i18n/appStrings.ts','APP_STRINGS'))]);
const lb = flatten(read('src/i18n/lb.json'));
const rows = read('scripts/lod/manifest.json');
const escape = s => s.replaceAll('|','\\|').replaceAll('\n',' ');
let report = '# Luxembourgish interface review\n\nGenerated by `npm run language:review`. Product choices: [catalog review](../scripts/lod/review.md).\n';
for (const section of new Set(lb.map(([key]) => key.split('.')[0]))) {
  report += `\n## ${section}\n\n| Key | English | Lëtzebuergesch |\n|---|---|---|\n`;
  report += lb.filter(([key]) => key.startsWith(section+'.')).map(([key,text]) => `| ${key} | ${escape(en.get(key) || 'MISSING')} | ${escape(text)} |`).join('\n')+'\n';
}
fs.writeFileSync('docs/luxembourgish-review.md',report);
if (!process.argv.includes('--spellcheck')) { console.log(`Generated review for ${lb.length} interface strings.`); process.exit(0); }
const dir=path.resolve('tmp/lb-spelling');
const source=read('scripts/language/source.json');
for(const [file, expected] of Object.entries(source.sha256)) {
  const actual=crypto.createHash('sha256').update(fs.readFileSync(path.join(dir,file))).digest('hex');
  if(actual!==expected)throw Error(`Dictionary checksum mismatch: ${file}`);
}
const contexts = [...lb.map(([id,text]) => ({id:`ui:${id}`, text})), ...rows.map(r=>({id:r.id,text:r.name}))];
const input = contexts.map(c=>'^'+c.text.replace(/\{\w+\}/g,' ').replace(/[\r\n]+/g,' ')).join('\n')+'\n';
const run=spawnSync('docker',['run','--rm','--network','none','-i','--mount',`type=bind,source=${dir},target=/dictionary,readonly`,'grocery-list-lb-spellcheck','-a','-i','UTF-8','-d','/dictionary/lb_LU'],{input,encoding:'utf8',maxBuffer:10*1024*1024});
if(run.status!==0)throw Error(run.error?.message || run.stderr || `Docker exited ${run.status}`);
const lines=run.stdout.replace(/\r/g,'').split('\n');
const version=lines.shift();
const blocks=lines.join('\n').trimEnd().split(/\n\n/);
if(blocks.length!==contexts.length)throw Error(`Hunspell context mismatch: ${blocks.length}/${contexts.length}`);
const exceptions=read('scripts/language/spelling-exceptions.json');
const findings=[];
for(let i=0;i<blocks.length;i++)for(const line of blocks[i].split('\n')){
  const match=/^[&#] (\S+)/.exec(line);
  if(match){ const c=contexts[i]; const reason=exceptions[`${c.id}:${match[1]}`]; findings.push({...c,word:match[1],reason}); }
}
const pending=findings.filter(f=>!f.reason);
let spelling=`# Luxembourgish spelling review\n\nDictionary: ${source.repository}, commit \`${source.commit}\`.\n\nChecker: ${version}\n\n${contexts.length} strings/product labels checked; ${findings.length} findings, ${pending.length} unresolved.\n\nChecks spelling only; grammar, n-rule context and shopping usage require editorial review. Foreign search aliases are deliberately excluded.\n\n| Context | Word | Text | Review |\n|---|---|---|---|\n`;
spelling+=findings.map(f=>`| ${f.id} | ${escape(f.word)} | ${escape(f.text)} | ${escape(f.reason || 'REVIEW REQUIRED')} |`).join('\n')+'\n';
fs.writeFileSync('docs/luxembourgish-spelling.md',spelling);
fs.writeFileSync('tmp/lb-spelling/findings.json',JSON.stringify(findings,null,2)+'\n');
console.log(`${contexts.length} entries checked; ${pending.length} unresolved findings. See docs/luxembourgish-spelling.md.`);
process.exitCode=pending.length?1:0;
